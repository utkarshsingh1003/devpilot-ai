import type { AnalysisResult, Category, Severity } from "./types";

export function formatNumber(value: number): string {
  return new Intl.NumberFormat("en-US").format(value);
}

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

export function formatDate(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return "Unknown";
  return new Intl.DateTimeFormat("en-US", {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(date);
}

export function severityLabel(severity: Severity): string {
  return severity.charAt(0).toUpperCase() + severity.slice(1);
}

export function categoryLabel(category: Category): string {
  const labels: Record<Category, string> = {
    security: "Security",
    bug: "Bug risk",
    maintainability: "Maintainability",
    performance: "Performance",
    testing: "Testing",
    style: "Style",
    documentation: "Documentation",
  };
  return labels[category];
}

export function toMarkdownReport(result: AnalysisResult): string {
  const lines: string[] = [];
  lines.push(`# DevPilot AI report — ${result.repo.fullName}`);
  lines.push("");
  lines.push(`- Generated: ${formatDate(result.generatedAt)}`);
  lines.push(`- Mode: ${result.mode === "demo" ? "Bundled demo repository" : "GitHub"}`);
  lines.push(`- Heuristic health score: ${result.summary.score}/100 (${result.summary.grade})`);
  lines.push(`- Files analyzed: ${result.summary.filesAnalyzed}`);
  lines.push(`- Lines analyzed: ${formatNumber(result.summary.totalLines)}`);
  lines.push(`- Findings: ${result.summary.findingsTotal}`);
  lines.push("");
  lines.push(
    "> This is a deterministic, heuristic review. It is not a security audit and does not prove the absence of bugs.",
  );
  lines.push("");

  if (result.ai.status === "ok" && result.ai.summary) {
    lines.push("## AI summary");
    lines.push("");
    lines.push(result.ai.summary);
    if (result.ai.priorities?.length) {
      lines.push("");
      for (const priority of result.ai.priorities) {
        lines.push(`- ${priority}`);
      }
    }
    lines.push("");
  }

  lines.push("## Findings");
  lines.push("");
  if (result.findings.length === 0) {
    lines.push("No rule-based findings were detected in the analyzed files.");
  } else {
    for (const finding of result.findings) {
      const location = finding.line > 0 ? `${finding.file}:${finding.line}` : finding.file;
      lines.push(`### [${severityLabel(finding.severity)}] ${finding.title}`);
      lines.push("");
      lines.push(`- Location: \`${location}\``);
      lines.push(`- Category: ${categoryLabel(finding.category)}`);
      lines.push(`- Detail: ${finding.description}`);
      lines.push(`- Suggestion: ${finding.suggestion}`);
      if (finding.snippet) {
        lines.push("");
        lines.push("```");
        lines.push(finding.snippet);
        lines.push("```");
      }
      lines.push("");
    }
  }

  if (result.warnings.length > 0) {
    lines.push("## Warnings");
    lines.push("");
    for (const warning of result.warnings) lines.push(`- ${warning}`);
    lines.push("");
  }

  lines.push("---");
  lines.push("Generated by DevPilot AI. No source code is stored by this app.");
  return lines.join("\n");
}
