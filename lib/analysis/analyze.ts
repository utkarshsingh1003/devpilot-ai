import {
  FILE_RULES,
  LINE_RULES,
  isCommentLine,
  lineNumberOf,
} from "./rules";
import { countLines } from "../languages";
import type {
  AnalysisResult,
  AnalysisSummary,
  AnalyzeInput,
  Category,
  Finding,
  Language,
  LanguageStat,
  Severity,
  SeverityCounts,
} from "../types";

const MAX_RETURNED_FINDINGS = 80;
const SEVERITY_WEIGHT: Record<Severity, number> = {
  critical: 10,
  high: 6,
  medium: 2,
  low: 0.5,
  info: 0.1,
};

const SEVERITY_ORDER: Record<Severity, number> = {
  critical: 0,
  high: 1,
  medium: 2,
  low: 3,
  info: 4,
};

function emptySeverityCounts(): SeverityCounts {
  return { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
}

function calculateScore(
  findings: Finding[],
  filesAnalyzed: number,
  totalLines: number,
): number {
  if (findings.length === 0) return 100;

  const weighted = findings.reduce(
    (total, finding) => total + SEVERITY_WEIGHT[finding.severity],
    0,
  );
  const perFile = weighted / Math.max(filesAnalyzed, 1);
  const perLine = (weighted / Math.max(totalLines, 100)) * 100;
  const penalty = Math.min(88, Math.round(perFile * 1.8 + perLine * 0.6));

  return Math.max(5, Math.min(100, 100 - penalty));
}

function gradeFor(score: number): AnalysisSummary["grade"] {
  if (score >= 90) return "A";
  if (score >= 80) return "B";
  if (score >= 70) return "C";
  if (score >= 60) return "D";
  return "F";
}

function languageStats(files: AnalyzeInput["files"]): {
  languages: LanguageStat[];
  totalLines: number;
  totalBytes: number;
} {
  const byLanguage = new Map<Language, { files: number; lines: number }>();
  let totalLines = 0;
  let totalBytes = 0;

  for (const file of files) {
    const lines = countLines(file.content);
    const bytes = new TextEncoder().encode(file.content).length;
    totalLines += lines;
    totalBytes += bytes;
    const current = byLanguage.get(file.language) ?? { files: 0, lines: 0 };
    byLanguage.set(file.language, {
      files: current.files + 1,
      lines: current.lines + lines,
    });
  }

  const languages = [...byLanguage.entries()]
    .map(([name, stats]) => ({
      name,
      files: stats.files,
      lines: stats.lines,
      percent: totalLines === 0 ? 0 : Math.round((stats.lines / totalLines) * 1000) / 10,
    }))
    .sort((a, b) => b.lines - a.lines);

  return { languages, totalLines, totalBytes };
}

/**
 * Deterministic, rule-based analysis. Every finding is derived from source text
 * that was actually provided. No finding is generated by an LLM or hardcoded.
 */
export function analyzeRepository(input: AnalyzeInput): AnalysisResult {
  const findings: Finding[] = [];
  const seen = new Set<string>();
  const warnings = [...(input.warnings ?? [])];

  const addFinding = (
    ruleId: string,
    data: Omit<Finding, "id" | "ruleId">,
  ): void => {
    const key = `${ruleId}:${data.file}:${data.line}`;
    if (seen.has(key)) return;
    seen.add(key);
    findings.push({
      id: key,
      ruleId,
      ...data,
    });
  };

  for (const file of input.files) {
    const lines = file.content.split(/\r\n|\r|\n/);

    for (let index = 0; index < lines.length; index += 1) {
      const line = lines[index];
      if (!line.trim()) continue;

      for (const rule of LINE_RULES) {
        if (rule.languages && !rule.languages.includes(file.language)) continue;
        if (rule.skipComments && isCommentLine(line, file.language)) continue;
        if (!rule.pattern.test(line)) continue;
        if (rule.skipIf?.(line)) continue;

        addFinding(rule.id, {
          title: rule.title,
          description: rule.description,
          severity: rule.severity,
          category: rule.category,
          file: file.path,
          line: index + 1,
          snippet: line.trim().slice(0, 240),
          suggestion: rule.suggestion,
          ...(rule.fix ? { fix: rule.fix } : {}),
        });
      }
    }

    // Multi-line empty catch blocks, e.g. `catch (error) {\n}`.
    const emptyCatch = /\bcatch\s*(?:\([^)]*\))?\s*\{\s*\}/g;
    for (const match of file.content.matchAll(emptyCatch)) {
      const index = match.index ?? 0;
      addFinding("bug.empty-catch", {
        title: "Empty catch block",
        description:
          "Errors are silently swallowed, which hides failures and makes production debugging difficult.",
        severity: "medium",
        category: "bug",
        file: file.path,
        line: lineNumberOf(file.content, index),
        snippet: match[0].replace(/\s+/g, " ").slice(0, 160),
        suggestion:
          "Handle the error, rethrow it with context, or log it through a structured logger.",
        fix: 'catch (error) {\n  logger.error("Operation failed", { error });\n}',
      });
    }

    // Python `except ...: pass` blocks.
    if (file.language === "Python") {
      const emptyExcept = /\bexcept[^\n]*:\s*\n\s*pass\b/g;
      for (const match of file.content.matchAll(emptyExcept)) {
        const index = match.index ?? 0;
        addFinding("bug.empty-except", {
          title: "Exception swallowed with pass",
          description:
            "The handler discards the exception without logging or recovery, so failures become invisible.",
          severity: "medium",
          category: "bug",
          file: file.path,
          line: lineNumberOf(file.content, index),
          snippet: match[0].replace(/\s+/g, " ").slice(0, 160),
          suggestion:
            "Log the exception with context, or re-raise it so the caller can decide how to recover.",
        });
      }
    }

    for (const rule of FILE_RULES) {
      if (!rule.test(file.content, lines)) continue;
      addFinding(rule.id, {
        title: rule.title,
        description: rule.description,
        severity: rule.severity,
        category: rule.category,
        file: file.path,
        line: rule.line?.(file.content, lines) ?? 1,
        snippet: rule.snippet(file.content, lines),
        suggestion: rule.suggestion,
        ...(rule.fix ? { fix: rule.fix } : {}),
      });
    }
  }

  if (input.files.length === 0) {
    warnings.push(
      "No supported source files were found. DevPilot analyzes TypeScript, JavaScript, and Python files.",
    );
  }

  if (!input.hasReadme && input.files.length > 0) {
    addFinding("documentation.missing-readme", {
      title: "No README detected",
      description:
        "The repository tree does not contain a root README, which makes onboarding and project context harder.",
      severity: "info",
      category: "documentation",
      file: "(repository)",
      line: 0,
      snippet: "No root README file was found in the fetched repository tree.",
      suggestion:
        "Add a README that explains the project purpose, setup steps, usage, and how to run tests.",
    });
  }

  if (input.testFiles === 0 && input.files.length > 0) {
    addFinding("testing.no-tests", {
      title: "No test files detected",
      description:
        "The repository tree does not contain files that match common test naming patterns.",
      severity: "info",
      category: "testing",
      file: "(repository)",
      line: 0,
      snippet: "No files matching *.test.*, *.spec.*, test_*.py, or tests/ were found.",
      suggestion:
        "Add focused unit tests for critical paths and wire them into CI so regressions are caught early.",
    });
  }

  if (input.treeTruncated) {
    warnings.push(
      "GitHub marked the repository tree as truncated. Analysis covers the files that were available.",
    );
  }
  if (input.filesSkipped > 0) {
    warnings.push(
      `${input.filesSkipped} eligible source file${input.filesSkipped === 1 ? "" : "s"} were skipped to stay within the analysis limits.`,
    );
  }

  const severityCounts = emptySeverityCounts();
  for (const finding of findings) {
    severityCounts[finding.severity] += 1;
  }

  findings.sort((a, b) => {
    const severity = SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity];
    if (severity !== 0) return severity;
    if (a.file !== b.file) return a.file.localeCompare(b.file);
    return a.line - b.line;
  });

  const { languages, totalLines, totalBytes } = languageStats(input.files);
  const score = calculateScore(findings, input.files.length, totalLines);
  const returned = findings.slice(0, MAX_RETURNED_FINDINGS);

  return {
    repo: input.repo,
    mode: input.repo.isDemo ? "demo" : "github",
    generatedAt: new Date().toISOString(),
    summary: {
      score,
      grade: gradeFor(score),
      filesAnalyzed: input.files.length,
      filesSkipped: input.filesSkipped,
      totalLines,
      totalBytes,
      testFiles: input.testFiles,
      hasTests: input.testFiles > 0,
      findingsTotal: findings.length,
      findingsReturned: returned.length,
      findingsTruncated: findings.length > returned.length,
      severityCounts,
      languages,
    },
    findings: returned,
    ai: { enabled: false, status: "disabled" },
    warnings: [...new Set(warnings)],
    limits: {
      maxFiles: input.limits?.maxFiles ?? 0,
      maxFileBytes: input.limits?.maxFileBytes ?? 0,
      maxTotalBytes: input.limits?.maxTotalBytes ?? 0,
      treeTruncated: input.treeTruncated,
    },
  };
}

export const CATEGORY_ORDER: Category[] = [
  "security",
  "bug",
  "maintainability",
  "testing",
  "performance",
  "style",
  "documentation",
];
